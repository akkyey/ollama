#!/bin/bash
# =========================================================================
# Ollama 推奨モデル一括ダウンロードスクリプト (バックグラウンド実行用)
# =========================================================================
set -euo pipefail

LOG_FILE="/home/irom/dev/ollama/download_models.log"

echo "================================================================" >> "$LOG_FILE"
echo "📥 モデルのダウンロードを開始します (開始時刻: $(date '+%Y-%m-%d %H:%M:%S'))" >> "$LOG_FILE"
echo "================================================================" >> "$LOG_FILE"

# ダウンロード対象モデル一覧
MODELS=(
  "qwen2.5:7b"
  "gemma3:12b"
  "llama3.1:8b"
  "gemma3:27b"
)

for MODEL in "${MODELS[@]}"; do
  echo "⏳ [$(date '+%Y-%m-%d %H:%M:%S')] ${MODEL} のダウンロードを開始します..." >> "$LOG_FILE"
  if docker exec ollama ollama pull "$MODEL" >> "$LOG_FILE" 2>&1; then
    echo "✅ [$(date '+%Y-%m-%d %H:%M:%S')] ${MODEL} のダウンロードが完了しました。" >> "$LOG_FILE"
  else
    echo "❌ [$(date '+%Y-%m-%d %H:%M:%S')] ${MODEL} のダウンロード中にエラーが発生しました。" >> "$LOG_FILE"
  fi
done

echo "================================================================" >> "$LOG_FILE"
echo "🎉 すべてのモデルのダウンロード処理が終了しました (終了時刻: $(date '+%Y-%m-%d %H:%M:%S'))" >> "$LOG_FILE"
echo "================================================================" >> "$LOG_FILE"
